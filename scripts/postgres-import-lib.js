function safeName(name) {
  if (!/^[a-z][a-z0-9_]{0,62}$/.test(name)) throw new Error(`Unsafe database identifier: ${name}`);
  return `"${name}"`;
}

function tablesInDependencyOrder(sqlite) {
  const tables = sqlite.prepare(`SELECT name, sql FROM sqlite_master
    WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`).all();
  const byName = new Map(tables.map(table => [table.name, table]));
  const visited = new Set();
  const visiting = new Set();
  const ordered = [];
  function visit(name) {
    if (visited.has(name)) return;
    if (visiting.has(name)) throw new Error(`Cyclic table dependency at ${name}`);
    visiting.add(name);
    for (const fk of sqlite.pragma(`foreign_key_list(${safeName(name)})`)) {
      if (!byName.has(fk.table)) throw new Error(`Missing referenced table ${fk.table}`);
      visit(fk.table);
    }
    visiting.delete(name);
    visited.add(name);
    ordered.push(byName.get(name));
  }
  for (const table of tables) { safeName(table.name); visit(table.name); }
  return ordered;
}

function postgresTableSql(name, sqliteSql) {
  safeName(name);
  return sqliteSql
    .replace(/^CREATE TABLE\s+(?:IF NOT EXISTS\s+)?(?:"[a-z0-9_]+"|[a-z0-9_]+)/i,
      `CREATE TABLE ${safeName(name)}`)
    .replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,
      'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/DEFAULT\s*\(datetime\('now'\)\)/gi,
      "DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))")
    .replace(/DEFAULT\s+""/gi, "DEFAULT ''")
    .replace(/!=/g, '<>');
}

function primaryKeyColumns(sqlite, name) {
  return sqlite.pragma(`table_info(${safeName(name)})`).filter(column => column.pk)
    .sort((a, b) => a.pk - b.pk).map(column => column.name);
}

function columns(sqlite, name) {
  return sqlite.pragma(`table_info(${safeName(name)})`);
}

function normalizePgRow(row, columnInfo) {
  const result = {};
  for (const column of columnInfo) {
    const value = row[column.name];
    if (value === null || value === undefined) result[column.name] = null;
    else if (/^INTEGER$/i.test(column.type)) {
      const number = Number(value);
      if (!Number.isSafeInteger(number)) throw new Error(`Unsafe integer in ${column.name}`);
      result[column.name] = number;
    } else if (/^REAL$/i.test(column.type)) result[column.name] = Number(value);
    else result[column.name] = value;
  }
  return result;
}

function sourceRows(sqlite, name) {
  const pk = primaryKeyColumns(sqlite, name);
  if (!pk.length) throw new Error(`Table ${name} has no primary key`);
  return sqlite.prepare(`SELECT * FROM ${safeName(name)} ORDER BY ${pk.map(safeName).join(', ')}`).all();
}

module.exports = { safeName, tablesInDependencyOrder, postgresTableSql,
  primaryKeyColumns, columns, normalizePgRow, sourceRows };
